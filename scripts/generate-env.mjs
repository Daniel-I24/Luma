#!/usr/bin/env node
/**
 * Writes src/environments/environment.deploy.ts (gitignored) from the build
 * environment (SUPABASE_URL, SUPABASE_ANON_KEY). Part of `npm run build:prod`
 * (Vercel), which builds with the `deploy` configuration that swaps it in;
 * the committed environment.prod.ts keeps its placeholders.
 * Fails when a variable is missing or when the key is a privileged one
 * (sb_secret_… or a JWT whose role is service_role): only the public
 * anon/publishable key may ever reach the browser. Never prints the key.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

export class EnvError extends Error {}

/** `role` claim of a JWT, or null when the value is not a decodable JWT. */
export function jwtRole(key) {
  const parts = key.split('.');
  if (parts.length !== 3) return null;
  try {
    const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
    return typeof payload.role === 'string' ? payload.role : null;
  } catch {
    return null;
  }
}

/** Validates the variables; returns the values to embed. */
export function readSupabaseEnv(env) {
  const url = env.SUPABASE_URL?.trim();
  const anonKey = env.SUPABASE_ANON_KEY?.trim();
  if (!url || !anonKey) throw new EnvError('SUPABASE_URL and SUPABASE_ANON_KEY are required.');

  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    throw new EnvError('SUPABASE_URL is not a valid URL.');
  }
  if (parsed.protocol !== 'https:') throw new EnvError('SUPABASE_URL must use https.');
  if (anonKey.startsWith('sb_secret_')) {
    throw new EnvError('SUPABASE_ANON_KEY is a secret key (sb_secret_…). Use the publishable/anon key.');
  }
  if (jwtRole(anonKey) === 'service_role') {
    throw new EnvError('SUPABASE_ANON_KEY is a service_role JWT. Use the anon key.');
  }
  return { url: parsed.origin, anonKey };
}

/** Generated file, relative to the repository root. */
export const TARGET_PATH = 'src/environments/environment.deploy.ts';

/** Source of environment.deploy.ts. */
export function renderEnvironment({ url, anonKey }) {
  return `// Generated by scripts/generate-env.mjs during the production build. Do not edit.
export const environment = {
  production: true,
  supabase: {
    url: ${JSON.stringify(url)},
    anonKey: ${JSON.stringify(anonKey)},
  },
} as const;
`;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  try {
    const target = fileURLToPath(new URL(`../${TARGET_PATH}`, import.meta.url));
    const values = readSupabaseEnv(process.env);
    writeFileSync(target, renderEnvironment(values));
    process.stdout.write(`generate-env: environment.deploy.ts written for ${values.url}\n`);
  } catch (error) {
    process.stderr.write(`generate-env: ${error instanceof EnvError ? error.message : 'unexpected error'}\n`);
    process.exit(1);
  }
}
