#!/usr/bin/env node
/**
 * Writes the public legal pages from the same texts the app shows
 * (public/i18n/es.json → legal.*, in the order of
 * src/app/features/legal/legal-documents.ts and with the versions of
 * src/app/shared/legal/legal-version.ts): one source, no copy to keep in step.
 *   public/legal/terminos.html, privacidad.html, reembolsos.html, eliminacion-datos.html
 * They need no session and no JavaScript (Meta, Wompi and the stores link to
 * them). LEGAL_CONTACT_EMAIL fills the contact e-mail.
 *   node scripts/build-legal.mjs          write the pages
 *   node scripts/build-legal.mjs --check  fail when the committed pages are stale
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { contactEmail } from './build-flags.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = (path) => readFileSync(`${ROOT}${path}`, 'utf8');

/** Public file of each document (Spanish slugs, the language of the pages). */
export const PAGES = { terms: 'terminos', privacy: 'privacidad', refunds: 'reembolsos', deletion: 'eliminacion-datos' };

const escape = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Section ids per document, read from legal-documents.ts (the app's order). */
export function sectionOrder(source = read('src/app/features/legal/legal-documents.ts')) {
  const order = {};
  for (const m of source.matchAll(/^\s+(\w+): \[([^\]]*)\]/gm)) order[m[1]] = [...m[2].matchAll(/'([a-z]+)'/g)].map((s) => s[1]);
  return order;
}

/** Versions per document, read from legal-version.ts. */
export function versions(source = read('src/app/shared/legal/legal-version.ts')) {
  return Object.fromEntries([...source.matchAll(/^\s+(\w+): '([^']+)'/gm)].map((m) => [m[1], m[2]]));
}

/** One page. */
export function renderPage(doc, legal, order, version, email) {
  const fill = (text) => escape(text.replaceAll('{{email}}', email || legal.contactPending));
  const sections = order.map((id) => {
    const section = legal[doc].sections[id];
    return `  <section>\n    <h2>${fill(section.title)}</h2>\n    <p>${fill(section.body)}</p>\n  </section>`;
  });
  const others = Object.entries(PAGES).filter(([key]) => key !== doc)
    .map(([key, slug]) => `<a href="/legal/${slug}.html">${escape(legal[key].title)}</a>`).join(' · ');
  return `<!doctype html>
<!-- Generated by scripts/build-legal.mjs from public/i18n/es.json. Do not edit. -->
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escape(legal[doc].title)} · Luma</title>
<style>
  :root { color-scheme: light dark; --fg: #1d2433; --muted: #4a5468; --bg: #fbf8f2; --note: #fff1cc; --link: #1f4fa3; }
  @media (prefers-color-scheme: dark) { :root { --fg: #eef1f7; --muted: #c2c9d6; --bg: #121a2b; --note: #4a3b10; --link: #9cc0ff; } }
  body { margin: 0; background: var(--bg); color: var(--fg); font: 1rem/1.6 system-ui, sans-serif; }
  main { max-width: 42rem; margin: 0 auto; padding: 1.5rem 1rem 3rem; overflow-wrap: anywhere; }
  h1 { font-size: clamp(1.5rem, 4vw, 2rem); line-height: 1.2; }
  h2 { font-size: 1.125rem; margin: 1.5rem 0 0.25rem; }
  p { margin: 0; color: var(--muted); }
  .note { background: var(--note); color: var(--fg); padding: 0.75rem; border-radius: 0.5rem; font-weight: 600; }
  a { color: var(--link); }
  nav { margin-top: 2rem; font-size: 0.875rem; }
</style>
</head>
<body>
<main>
  <h1>${escape(legal[doc].title)}</h1>
  <p class="note">${escape(legal.draftNotice)}</p>
  <p>${escape(legal.version.replace('{{version}}', version))}</p>
${sections.join('\n')}
  <nav>${others}</nav>
</main>
</body>
</html>
`;
}

/** Every page: [path, html]. */
export function renderAll(env = process.env) {
  const legal = JSON.parse(read('public/i18n/es.json')).legal;
  const order = sectionOrder();
  const version = versions();
  const email = contactEmail(env);
  return Object.entries(PAGES).map(([doc, slug]) => [`public/legal/${slug}.html`, renderPage(doc, legal, order[doc], version[doc], email)]);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const pages = renderAll(check ? {} : process.env);
  const stale = pages.filter(([path, html]) => {
    try {
      return read(path) !== html;
    } catch {
      return true;
    }
  });
  if (check) {
    for (const [path] of stale) process.stdout.write(`${path} is stale: run npm run build:legal\n`);
    process.stdout.write(stale.length ? `build-legal: ${stale.length} stale page(s)\n` : 'build-legal: ok\n');
    process.exitCode = stale.length ? 1 : 0;
  } else {
    mkdirSync(`${ROOT}public/legal`, { recursive: true });
    for (const [path, html] of pages) writeFileSync(`${ROOT}${path}`, html);
    process.stdout.write(`build-legal: ${pages.length} pages written to public/legal\n`);
  }
}
